#!/usr/bin/env python3
"""Generate tests/stub.json: 10-frame synthetic scene (camera + 2 players) in
demo_extract output format. Used to drive both import branches without a demo."""
import json, math, os

frames = []
cam = []
for tick in range(0, 1000, 100):
    t = tick / 100.0
    frames.append({
        "tick": tick,
        "time": t,
        "entities": [
            {
                "index": 1, "player": True,
                "origin": [128.0 + tick * 2.0, 64.0, 32.0 + math.sin(tick / 100.0) * 16],
                "angles": [0.0, 45.0, 0.0],
                "velocity": [200.0, 0, 0],
                "modelindex": 2, "sequence": (tick // 200) % 3, "frame": 0.25,
                "animtime": t - 0.05, "framerate": 30.0, "body": 0, "cycle": 1.5,
            },
            {
                "index": 2, "player": True,
                "origin": [1024.0 - tick * 3.0, 512.0, 64.0],
                "angles": [0.0, 180.0, 0.0],
                "velocity": [-300.0, 0, 0],
                "modelindex": 2, "sequence": 1, "frame": 0.0,
                "animtime": t - 0.03, "framerate": 30.0, "body": 0, "cycle": 0.9,
            },
        ],
    })
    if tick % 200 == 0:
        cam.append({
            "tick": tick, "time": t,
            "origin": [256.0, 128.0, 96.0 + tick * 0.05],
            "viewangles": [5.0, 90.0 + tick * 0.1, 0.0],
            "fov": 90.0, "source": 0,
        })

doc = {
    "demo": "stub.json", "map": "de_test", "game": "cstrike",
    "demo_protocol": 5, "net_protocol": 47, "tick_interval": 1,
    "max_clients": 32, "frames_parsed": 10,
    "notes": "stub generated by tools/make_stub.py",
    "camera": cam,
    "frames": frames,
}
path = os.path.join(os.path.dirname(__file__), '..', 'tests', 'stub.json')
with open(path, 'w', encoding='utf-8') as f:
    json.dump(doc, f, indent=1)
print('wrote', os.path.abspath(path))
